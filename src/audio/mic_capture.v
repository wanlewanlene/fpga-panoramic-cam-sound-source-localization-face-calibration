//-----------------------------------------------------------------------------
// mic_capture.v
//   Takes the 8 raw I2S words from i2s_rx_8slot and produces 7 named
//   microphone channels (6 ring mics + 1 center reference) at a decimated rate.
//
//   CHANNEL MAP  (verified against the Sipeed schematic)
//   ----------------------------------------------------
//   Raw words arrive as slot0..slot7 = (lane0..lane3) x (WS-low, WS-high).
//
//   Source: Sipeed-R6+1_MicArray_11.16 (Schematic).pdf  -- see doc/
//      U7  + U8  : MSM261S4030H0, both SD -> MIC_DAT0  -> FPGA mic_array_d[0]
//      U13 + U14 : MSM261S4030H0, both SD -> MIC_DAT1  -> FPGA mic_array_d[1]
//      U19 + U20 : MSM261S4030H0, both SD -> MIC_DAT2  -> FPGA mic_array_d[2]
//      U1        : MSM261S4030H0, SD      -> MIC_DAT3  -> FPGA mic_array_d[3]
//                  (silkscreen "Center MIC", radius 0)
//
//   So each of lanes 0..2 carries TWO ring mics, separated by the WS phase
//   (the two chips on one lane are strapped to opposite L/R levels).  Lane 3
//   carries the single CENTER mic and is the natural TDOA reference.
//
//   mics 0..5 = ring, 60 degrees apart, radius R = 40 mm (sch annotation
//   "MIC R=40mm").  mic6 = center reference.
//
//   !! ONE THING STILL UNVERIFIED !!
//   Which of the two chips on a shared lane sits on WS-low vs WS-high
//   depends on the L/R strap, which the PDF exports as a net label with no
//   visible pull resistor.  The default below assumes the lower designator
//   (U7/U13/U19) is WS-low.  If a brought-up board shows two adjacent mics
//   swapped, flip the corresponding MAPx between the (2k)/(2k+1) slots --
//   nothing else in the design needs to change.
//
//   DECIMATION
//   ----------
//   I2S ws rate = the sample rate produced by the array (typically 16 kHz or
//   48 kHz -- it is generated BY the array board, the FPGA only receives).
//   The FPGA simply latches every frame.  DECIM=1 => one PCM sample per frame.
//   Set DECIM>1 only if you want to down-sample an over-fast array.
//-----------------------------------------------------------------------------
`timescale 1ns / 1ps

module mic_capture #(
    parameter integer DATA_W = 24,
    parameter integer NBAND  = 4,          // sub-band count (subband4 / tdoa_engine)
    parameter integer NCH    = 7,          // channels, structural (6 ring + centre)
    parameter integer DECIM  = 1,          // frames per output sample (>=1)
    // NOTE (2026-10-15): a parameter `NCH = 7` used to sit here.  It was
    // declared and never referenced anywhere in this file -- the channel
    // count is STRUCTURAL, fixed by the seven named outputs ch0..ch6 and the
    // seven channel-map parameters MAP0..MAP6, and top.v even passed
    // `.NCH(7)` explicitly, which made it look like a live knob.  Editing it
    // changed nothing, which is the same trap that CNT_W in i2s_rx_8slot.v
    // and the "x/2" shift in mic_cond used to be.  Removed rather than
    // "used", because there is nothing sensible for it to control.
    // ---- conditioning filter (identical on every channel) ----
    // See the FILTER CHAIN section at the bottom of this file.  The filtered
    // channels (fch*) feed the TDOA engine; the raw ones (ch*) still feed the
    // UART, so the PC tool keeps seeing exactly what the microphones output.
    // FILT_EN = 0 bypasses the filter (for A/B measurements).
    //
    // Identical coefficients on all seven channels is not an optimisation,
    // it is the requirement: the plane-wave TDOA survives any LTI filter as
    // long as the reference and the ring microphone see the SAME filter.
    parameter integer FILT_EN = 1,
    // ---- channel map: which raw slot feeds each logical channel ----
    // slot0..slot7 = lane0..lane3 x WS-low/WS-high.
    //   mic0 = lane0 ws-low  mic1 = lane0 ws-high   (U7 / U8)
    //   mic2 = lane1 ws-low  mic3 = lane1 ws-high   (U13 / U14)
    //   mic4 = lane2 ws-low  mic5 = lane2 ws-high   (U19 / U20)
    //   mic6 = lane3 ws-low  = CENTER reference     (U1)
    parameter [2:0] MAP0 = 3'd0,   // U7   ring
    parameter [2:0] MAP1 = 3'd1,   // U8   ring
    parameter [2:0] MAP2 = 3'd2,   // U13  ring
    parameter [2:0] MAP3 = 3'd3,   // U14  ring
    parameter [2:0] MAP4 = 3'd4,   // U19  ring
    parameter [2:0] MAP5 = 3'd5,   // U20  ring
    parameter [2:0] MAP6 = 3'd6    // U1   CENTER (reference)
) (
    input  wire                     rst_n,
    input  wire                     bck,
    input  wire                     ws,
    input  wire [3:0]               d_in,

    // 7 channels, signed 24-bit, updated every frame_stb*DECIM
    output reg  signed [DATA_W-1:0] ch0,
    output reg  signed [DATA_W-1:0] ch1,
    output reg  signed [DATA_W-1:0] ch2,
    output reg  signed [DATA_W-1:0] ch3,
    output reg  signed [DATA_W-1:0] ch4,
    output reg  signed [DATA_W-1:0] ch5,
    output reg  signed [DATA_W-1:0] ch6,   // center reference (U1, lane3)

    // CONDITIONED copies of the same seven channels (same mapping, same
    // sample instant -- see the FILTER CHAIN section), for the TDOA engine.
    // The engine correlates the reference against a ring microphone, so both
    // sides of every correlation must come from THIS set; mixing a raw
    // channel with a filtered one would inject the filter's own group delay
    // into the TDOA.
    output wire signed [DATA_W-1:0] fch0,
    output wire signed [DATA_W-1:0] fch1,
    output wire signed [DATA_W-1:0] fch2,
    output wire signed [DATA_W-1:0] fch3,
    output wire signed [DATA_W-1:0] fch4,
    output wire signed [DATA_W-1:0] fch5,
    output wire signed [DATA_W-1:0] fch6,  // center reference (U1, lane3)

    // ---- sub-band PHAT analysis (2026-10-19) ----
    // Four one-pole bands per channel, packed flat: band b (0..3) of channel
    // c (0..6) lives at band_out[NBAND*DATA_W*c + DATA_W*b +: DATA_W].
    // Band b=0 is the lowest.  These feed the sub-band correlator; the
    // broadband conditioned reference (fch6) is kept separately for the
    // energy gate, whose scale must not change (see top.v ANY_SND_E).
    output wire signed [NBAND*DATA_W*NCH-1:0] band_out,

    output reg                      ch_stb,   // 1 bck: new sample set ready
    output reg  [15:0]              frame_cnt,// free-running frame counter (debug)

    //------------------------------------------------------------------
    //  DIAGNOSTIC: the OTHER lane-3 phase (added 2026-10-15).
    //
    //  Lane 3 carries the single CENTRE microphone, and which of the two WS
    //  phases it drives is set by its L/R strap -- the one thing the board
    //  schematic does not pin down.  MAP6 selects which phase we TREAT as the
    //  reference; if the strap is the other way, the selected phase is a
    //  floating (tristated, 100k-pulled) line and the reference reads a
    //  constant zero: every correlation is then exactly 0, any_valid stays 0,
    //  the solver never starts, and the board shows exactly
    //      leds[0] = 1   (framing fine)      leds[1] = blinking (no ref data)
    //      leds[2] = 0   (no peak)           leds[3] = 0
    //  -- which is useless, because "the reference is dead" and "the whole
    //  array is dead" look identical.
    //
    //  This port therefore exposes the phase MAP6 did NOT select, so top.v can
    //  monitor both and the lamps can say WHICH one is alive.  It is a pure
    //  wire out of the demux: no behaviour change for any existing consumer.
    //------------------------------------------------------------------
    output wire signed [DATA_W-1:0] slot_l3_other,

    output wire                     locked    // I2S framing acquired
);

    // raw slots
    wire signed [DATA_W-1:0] s0, s1, s2, s3, s4, s5, s6, s7;
    wire                     fstb;
    wire                     ws_phase;

    i2s_rx_8slot #(
        .DATA_W (DATA_W),
        .SLOT_W (32)
    ) u_i2s_rx (
        .rst_n    (rst_n),
        .bck      (bck),
        .ws       (ws),
        .d_in     (d_in),
        .slot0    (s0), .slot1 (s1), .slot2 (s2), .slot3 (s3),
        .slot4    (s4), .slot5 (s5), .slot6 (s6), .slot7 (s7),
        .frame_stb(fstb),
        .ws_phase (ws_phase),
        .locked   (locked)
    );

    // channel map constants (see MAP* parameters above)
    localparam [2:0] map0 = MAP0;
    localparam [2:0] map1 = MAP1;
    localparam [2:0] map2 = MAP2;
    localparam [2:0] map3 = MAP3;
    localparam [2:0] map4 = MAP4;
    localparam [2:0] map5 = MAP5;
    localparam [2:0] map6 = MAP6;

    function signed [DATA_W-1:0] pick;
        input [2:0] idx;
        input signed [DATA_W-1:0] a0,a1,a2,a3,a4,a5,a6,a7;
        begin
            case (idx)
                3'd0: pick = a0;
                3'd1: pick = a1;
                3'd2: pick = a2;
                3'd3: pick = a3;
                3'd4: pick = a4;
                3'd5: pick = a5;
                3'd6: pick = a6;
                3'd7: pick = a7;
            endcase
        end
    endfunction

    //------------------------------------------------------------------
    // Decimator + conditioning
    //------------------------------------------------------------------
    localparam integer DW = (DECIM <= 1) ? 1 : $clog2(DECIM);

    reg [DW-1:0] dec_cnt;

    // One combinational pick per logical channel, so the raw UART path and
    // the filtered engine path consume the SAME sample of the SAME frame.
    wire signed [DATA_W-1:0] raw0 = pick(map0, s0,s1,s2,s3,s4,s5,s6,s7);
    wire signed [DATA_W-1:0] raw1 = pick(map1, s0,s1,s2,s3,s4,s5,s6,s7);
    wire signed [DATA_W-1:0] raw2 = pick(map2, s0,s1,s2,s3,s4,s5,s6,s7);
    wire signed [DATA_W-1:0] raw3 = pick(map3, s0,s1,s2,s3,s4,s5,s6,s7);
    wire signed [DATA_W-1:0] raw4 = pick(map4, s0,s1,s2,s3,s4,s5,s6,s7);
    wire signed [DATA_W-1:0] raw5 = pick(map5, s0,s1,s2,s3,s4,s5,s6,s7);
    wire signed [DATA_W-1:0] raw6 = pick(map6, s0,s1,s2,s3,s4,s5,s6,s7);

    // the lane-3 phase MAP6 did NOT pick -- the diagnostic port (see above).
    // MAP6 is only ever 6 (=s6) or 7 (=s7); anything else leaves s7 exposed,
    // which is the safe answer because such a configuration is broken anyway
    // and this at least keeps the monitor pointed at a real lane-3 phase.
    assign slot_l3_other = (map6 == 3'd6) ? s7 : s6;

    // this frame yields a new set of output samples
    wire smp_en = fstb && (DECIM <= 1 || (dec_cnt == DECIM-1));

    always @(posedge bck or negedge rst_n) begin
        if (!rst_n) begin
            ch0 <= 0; ch1 <= 0; ch2 <= 0; ch3 <= 0;
            ch4 <= 0; ch5 <= 0; ch6 <= 0;
            ch_stb    <= 1'b0;
            dec_cnt   <= { DW {1'b0} };
            frame_cnt <= 16'd0;
        end else begin
            ch_stb <= 1'b0;

            if (fstb) begin
                frame_cnt <= frame_cnt + 1'b1;

                if (DECIM <= 1 || dec_cnt == DECIM-1) begin
                    dec_cnt <= { DW {1'b0} };
                    ch0 <= raw0;
                    ch1 <= raw1;
                    ch2 <= raw2;
                    ch3 <= raw3;
                    ch4 <= raw4;
                    ch5 <= raw5;
                    ch6 <= raw6;
                    ch_stb <= 1'b1;
                end else begin
                    dec_cnt <= dec_cnt + 1'b1;
                end
            end
        end
    end

    //------------------------------------------------------------------
    // CONDITIONING FILTER CHAIN -- one instance per channel
    //
    // The correlator only ever compares the reference against a ring
    // microphone, so this chain -- not the correlator -- decides how good
    // the correlation peak is.  Three multiplier-free first-order sections:
    //
    //   S1  DC block / rumble high-pass   pole 0.984375, fc ~ 120 Hz @ 48.8k
    //       Removes microphone DC offset, table thumps, HVAC rumble.
    //       Low-frequency content that is coherent across the array but is
    //       NOT a plane wave is the classic reason a bearing drifts towards
    //       the array centre.
    //   S2  pre-emphasis (whitening)      zero 0.9375, +6 dB/oct above ~500 Hz
    //       Speech falls at roughly 6 dB/oct, so this flattens the spectrum
    //       reaching the correlator.  It is a one-zero stand-in for the PHAT
    //       weighting of a frequency-domain GCC and is what turns a broad,
    //       reverb-smeared correlation peak into a sharp one the parabolic
    //       interpolator can actually locate.
    //   S3  anti-hiss low-pass            fc ~ 6 kHz
    //       Caps the band after the emphasis, so the +6 dB/oct tilt never
    //       amplifies hiss into the peak search.
    //
    // Every coefficient is a sum of powers of two: no multiplier, no
    // coefficient RAM, nothing to tune.
    //
    // HEADROOM -- CORRECTED 2026-10-11.  This used to claim "the input is
    // halved on the way in because the differentiator section has a gain of
    // 2 at Nyquist; with that factor every intermediate stays inside 26
    // bits".  NO HALVING ACTUALLY HAPPENS (see the xg note in mic_cond
    // below -- the shift pair cancels).  Recomputing with the chain at FULL
    // amplitude, |x| <= A = 2^23:
    //     |s1| <= 3.03 A     |s2| <= 3.12 A     |s3| <= 3.12 A
    // against the 26-bit limit of 2^25 = 4 A.  So it DOES fit, but with
    // about 1.3x margin rather than the 2.6x the old comment implied, and
    // the output clamp is therefore a real guard, not just cold-start
    // belt-and-braces.  Changing the amplitude here would change the
    // correlation magnitude (never the TDOA, which is scale-invariant), so
    // it is left alone until a testbench or a capture says otherwise.
    //------------------------------------------------------------------
    wire signed [DATA_W-1:0] f0, f1, f2, f3, f4, f5, f6;

    mic_cond #(.DATA_W(DATA_W)) u_c0
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw0), .y(f0));
    mic_cond #(.DATA_W(DATA_W)) u_c1
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw1), .y(f1));
    mic_cond #(.DATA_W(DATA_W)) u_c2
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw2), .y(f2));
    mic_cond #(.DATA_W(DATA_W)) u_c3
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw3), .y(f3));
    mic_cond #(.DATA_W(DATA_W)) u_c4
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw4), .y(f4));
    mic_cond #(.DATA_W(DATA_W)) u_c5
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw5), .y(f5));
    mic_cond #(.DATA_W(DATA_W)) u_c6
              (.bck(bck), .rst_n(rst_n), .en(smp_en), .x(raw6), .y(f6));

    assign fch0 = FILT_EN ? f0 : raw0;
    assign fch1 = FILT_EN ? f1 : raw1;
    assign fch2 = FILT_EN ? f2 : raw2;
    assign fch3 = FILT_EN ? f3 : raw3;
    assign fch4 = FILT_EN ? f4 : raw4;
    assign fch5 = FILT_EN ? f5 : raw5;
    assign fch6 = FILT_EN ? f6 : raw6;

    //------------------------------------------------------------------
    // SUB-BAND ANALYSIS (2026-10-19)
    //
    // Each conditioned channel is split into NBAND one-pole bands by a
    // subband4 tree.  The tree is fed the SAME signal that fch* carries
    // (FILT_EN already applied), so the band split and the broadband energy
    // reference are taken from identical samples -- the same rule that made
    // fch the engine input before: a filter common to both sides of a
    // correlation cannot move its peak.
    //
    // Band b of channel c -> band_out[NBAND*DATA_W*c + DATA_W*b +: DATA_W].
    //------------------------------------------------------------------
    wire signed [DATA_W-1:0] cond [0:NCH-1];
    assign cond[0] = FILT_EN ? f0 : raw0;
    assign cond[1] = FILT_EN ? f1 : raw1;
    assign cond[2] = FILT_EN ? f2 : raw2;
    assign cond[3] = FILT_EN ? f3 : raw3;
    assign cond[4] = FILT_EN ? f4 : raw4;
    assign cond[5] = FILT_EN ? f5 : raw5;
    assign cond[6] = FILT_EN ? f6 : raw6;

    genvar gc;
    generate
        for (gc = 0; gc < NCH; gc = gc + 1) begin : g_band
            wire signed [DATA_W-1:0] b0, b1, b2, b3;
            subband4 #(.DATA_W(DATA_W)) u_sb (
                .clk  (bck),
                .rst_n(rst_n),
                .en   (smp_en),
                .x    (cond[gc]),
                .b0   (b0), .b1 (b1), .b2 (b2), .b3 (b3)
            );
            assign band_out[NBAND*DATA_W*gc + DATA_W*0 +: DATA_W] = b0;
            assign band_out[NBAND*DATA_W*gc + DATA_W*1 +: DATA_W] = b1;
            assign band_out[NBAND*DATA_W*gc + DATA_W*2 +: DATA_W] = b2;
            assign band_out[NBAND*DATA_W*gc + DATA_W*3 +: DATA_W] = b3;
        end
    endgenerate

endmodule


//-----------------------------------------------------------------------------
// mic_cond -- conditioning chain for ONE microphone channel.
//
//   y = S3( S2( S1(x) ) )   with
//     S1: y1 = xg - hx1 + hy - (hy >>> 6)
//     S2: y2 = (y1 >>> 1) - (ex1 >>> 1) + (ex1 >>> 5)
//     S3: y3 = ly + (dl >>> 1) + (dl >>> 5) + (dl >>> 7),  dl = y2 - ly
//
//   All three sections run on `en` -- one cycle per audio frame -- so the
//   whole chain costs six shifts and six adds per channel per sample.  No
//   DSP block, no coefficient RAM, nothing to configure at run time.
//
//   WIDTH (2026-10-15): port and internal widths are derived from DATA_W.
//   They used to be hard-coded at 24 / 26, which happened to match
//   mic_capture's DATA_W = 24 -- but the parameter was silently ignored, so
//   changing DATA_W would have truncated the filter chain with no warning
//   from any tool.  The guard bits are DATA_W+2, as before.
//-----------------------------------------------------------------------------
module mic_cond #(
    parameter integer DATA_W = 24
) (
    input  wire                     bck,
    input  wire                     rst_n,
    input  wire                     en,
    input  wire signed [DATA_W-1:0] x,
    output reg  signed [DATA_W-1:0] y
);
    // two guard bits over the sample
    localparam integer IW = DATA_W + 2;

    // xg used to read   {x[23], x, 1'b0} >>> 1   with the comment "x / 2".
    // A left shift immediately undone by a right shift is a NO-OP, so the
    // chain ran at FULL amplitude and every headroom argument that depended
    // on the halving rested on a false premise.  Written as a plain sign
    // extension so the code says what it does.  If the halving is ever
    // actually wanted, use  {{2{x[DATA_W-1]}}, x} >>> 1  which buys 6 dB of
    // margin but also halves the correlation magnitude.
    wire signed [IW-1:0] xg = {{2{x[DATA_W-1]}}, x};

    // ---- S1: DC block / rumble high-pass (pole 1 - 2^-6) ----
    reg  signed [IW-1:0] hx1;
    reg  signed [IW-1:0] hy;
    wire signed [IW-1:0] s1 = xg - hx1 + hy - (hy >>> 6);

    // ---- S2: pre-emphasis (zero 15/16, unity peak gain) ----
    reg  signed [IW-1:0] ex1;
    wire signed [IW-1:0] s2 = (s1 >>> 1) - (ex1 >>> 1) + (ex1 >>> 5);

    // ---- S3: anti-hiss low-pass (one-pole, c = 0.5390625) ----
    reg  signed [IW-1:0] ly;
    wire signed [IW-1:0] dl = s2 - ly;
    wire signed [IW-1:0] s3 = ly + (dl >>> 1) + (dl >>> 5) + (dl >>> 7);

    // Belt-and-braces output clamp: a cold-start transient is the only way
    // s3 can leave the DATA_W-bit range, and wrapping there would inject a
    // large false correlation peak.
    localparam signed [IW-1:0] Y_MAX =  (1 <<< (DATA_W-1)) - 1;
    localparam signed [IW-1:0] Y_MIN = -(1 <<< (DATA_W-1));
    wire signed [IW-1:0] s3_cl = (s3 > Y_MAX) ? Y_MAX
                               : (s3 < Y_MIN) ? Y_MIN : s3;

    always @(posedge bck or negedge rst_n) begin
        if (!rst_n) begin
            hx1 <= {IW{1'b0}};
            hy  <= {IW{1'b0}};
            ex1 <= {IW{1'b0}};
            ly  <= {IW{1'b0}};
            y   <= {DATA_W{1'b0}};
        end else if (en) begin
            hx1 <= xg;
            hy  <= s1;
            ex1 <= s1;
            ly  <= s3;
            y   <= s3_cl[DATA_W-1:0];
        end
    end

endmodule
